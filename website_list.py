def get_all_urls():
    """Return a deduplicated list of all ecommerce websites."""
    return list(set(ALL_ECOMMERCE_WEBSITES))


def get_urls_by_country(country_name):
    """Get URLs for a specific country."""
    return ECOMMERCE_BY_COUNTRY.get(country_name, [])


def get_countries():
    """Get list of all countries in the database."""
    return list(ECOMMERCE_BY_COUNTRY.keys())


